// npm run brand — regenerates every EliteStream brand image from one source:
//   assets/brand/elitestream-logo.png (2048 x 2048 RGBA, transparent background: mark above the
//   "elitestream" wordmark). Uses ffmpeg (PATH, or FFMPEG=<path>).
// Writes (all committed; the build only copies them):
//   src/components/brand-assets.ts                       mark + wordmark as PNG data URIs (in-app logo)
//   tizen/icon.png                                       Samsung app icon, 512 x 512
//   android/app/src/main/res/drawable-nodpi/ic_launcher.png  Android app icon, 192 x 192
//   android/app/src/main/res/drawable-nodpi/tv_banner.png    Android TV launcher banner, 640 x 360
// Crop boxes are in source pixels and were checked visually against the source image.
import { execFileSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync, existsSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const FFMPEG = process.env.FFMPEG || 'ffmpeg';
const SRC = join(root, 'assets', 'brand', 'elitestream-logo.png');
const BG = '0x10131A'; // app background (dark), used behind icons and the banner

const MARK = 'crop=900:900:575:440';    // the E / play / signal mark
const WORD = 'crop=1480:280:280:1335';  // the "elitestream" wordmark
const LOGO = 'crop=1480:1180:280:450';  // mark above wordmark

if (!existsSync(SRC)) {
  console.error('brand: source image missing: ' + SRC);
  process.exit(1);
}

function ff(args) {
  execFileSync(FFMPEG, ['-v', 'error', '-y'].concat(args), { stdio: 'inherit' });
}

/** Source crop scaled to w x h (h = -2 keeps the aspect), transparent PNG. */
function transparent(out, crop, w, h) {
  ff(['-i', SRC, '-vf', crop + ',scale=' + w + ':' + h + ':flags=lanczos,format=rgba', '-frames:v', '1', out]);
}

/** Source crop scaled to cw x ch and centred on a dark w x h canvas, opaque PNG. */
function onDark(out, w, h, crop, cw, ch) {
  const x = Math.round((w - cw) / 2);
  const y = Math.round((h - ch) / 2);
  ff(['-f', 'lavfi', '-i', 'color=c=' + BG + ':s=' + w + 'x' + h, '-i', SRC,
    '-filter_complex', '[1]' + crop + ',scale=' + cw + ':' + ch + ':flags=lanczos[l];[0][l]overlay=' + x + ':' + y,
    '-frames:v', '1', '-pix_fmt', 'rgb24', out]);
}

const tmp = mkdtempSync(join(tmpdir(), 'es-brand-'));
try {
  // In-app logo: mark 128 px (shown at 56-64 px), wordmark 72 px high (shown at 36 px).
  transparent(join(tmp, 'mark.png'), MARK, 128, 128);
  transparent(join(tmp, 'word.png'), WORD, -2, 72);
  const uri = (f) => 'data:image/png;base64,' + readFileSync(join(tmp, f)).toString('base64');
  writeFileSync(join(root, 'src', 'components', 'brand-assets.ts'),
    '// GENERATED by scripts/brand-assets.mjs (npm run brand) from assets/brand/elitestream-logo.png. Do not edit.\n' +
    '/** EliteStream mark (E / play / signal), 128 x 128 PNG, transparent. */\n' +
    "export const BRAND_MARK_PNG = '" + uri('mark.png') + "';\n" +
    '/** "elitestream" wordmark, 72 px high PNG, transparent. */\n' +
    "export const BRAND_WORDMARK_PNG = '" + uri('word.png') + "';\n");

  // App icons and the Android TV banner: on the app's dark background.
  onDark(join(root, 'tizen', 'icon.png'), 512, 512, MARK, 400, 400);
  const res = join(root, 'android', 'app', 'src', 'main', 'res', 'drawable-nodpi');
  mkdirSync(res, { recursive: true });
  onDark(join(res, 'ic_launcher.png'), 192, 192, MARK, 150, 150);
  onDark(join(res, 'tv_banner.png'), 640, 360, LOGO, 376, 300);
} finally {
  rmSync(tmp, { recursive: true, force: true });
}
console.log('brand: OK (brand-assets.ts, tizen/icon.png, Android ic_launcher.png and tv_banner.png)');
