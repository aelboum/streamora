// Builds the static EliteStream website into dist/:
//   one directory per page (/features/index.html …), 404.html, hashed CSS and JS, the design's
//   assets, the self-hosted fonts (only the weights the design uses), _headers and robots/sitemap.
// Usage: npm run build   (no network access; fonts come from the pinned @fontsource packages)
import { createHash } from 'node:crypto';
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { PAGES, SITE_URL } from './src/data.mjs';
import { layout, href } from './src/layout.mjs';
import { RENDER, notFound } from './src/pages.mjs';

const root = dirname(fileURLToPath(import.meta.url));
const out = join(root, 'dist');
rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });

function hashed(name, text) {
  const h = createHash('sha256').update(text).digest('hex').slice(0, 10);
  const file = name.replace(/\.(\w+)$/, '.' + h + '.$1');
  writeFileSync(join(out, file), text);
  return '/' + file;
}

const css = hashed('styles.css', readFileSync(join(root, 'src/styles.css'), 'utf8'));
const js = hashed('site.js', readFileSync(join(root, 'src/site.js'), 'utf8'));
const assets = { css, js };

for (const page of PAGES) {
  const html = layout({ page, body: RENDER[page](), assets });
  const dir = page === 'home' ? out : join(out, page);
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, 'index.html'), html);
}
writeFileSync(join(out, '404.html'), layout({ page: '404', body: notFound(), assets }));

// Design assets (logo mark and favicon from the Claude Design project) and static files.
cpSync(join(root, 'public'), out, { recursive: true });

// Fonts: the design's families and weights only (Sora 400/600, DM Sans variable, JetBrains Mono 400).
const fonts = [
  '@fontsource/sora/files/sora-latin-400-normal.woff2',
  '@fontsource/sora/files/sora-latin-600-normal.woff2',
  '@fontsource-variable/dm-sans/files/dm-sans-latin-opsz-normal.woff2',
  '@fontsource/jetbrains-mono/files/jetbrains-mono-latin-400-normal.woff2'
];
mkdirSync(join(out, 'fonts'), { recursive: true });
for (const f of fonts) {
  const src = join(root, 'node_modules', f);
  if (!existsSync(src)) { throw new Error('missing font ' + f + ' (run npm install)'); }
  cpSync(src, join(out, 'fonts', f.split('/').pop()));
}
writeFileSync(join(out, 'fonts', 'LICENSE.txt'), 'Sora, DM Sans and JetBrains Mono: SIL Open Font License 1.1 (via the @fontsource packages).\n');

writeFileSync(join(out, 'robots.txt'), 'User-agent: *\nAllow: /\nSitemap: ' + SITE_URL + '/sitemap.xml\n');
writeFileSync(join(out, 'sitemap.xml'), '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' +
  PAGES.map((p) => '  <url><loc>' + SITE_URL + href(p) + '</loc></url>').join('\n') + '\n</urlset>\n');

// The phone pairing page (relay/public, pair.elitestreamplayer.com) uses the same design system:
// the same stylesheet, fonts and logo, copied there so both pages come from one source.
const relayPublic = join(root, '..', 'relay', 'public');
if (existsSync(relayPublic)) {
  writeFileSync(join(relayPublic, 'site.css'), '/* GENERATED by website/build.mjs from website/src/styles.css — do not edit here. */\n' + readFileSync(join(root, 'src/styles.css'), 'utf8'));
  cpSync(join(out, 'fonts'), join(relayPublic, 'fonts'), { recursive: true });
  cpSync(join(root, 'public', 'assets'), join(relayPublic, 'assets'), { recursive: true });
}

console.log('built ' + (PAGES.length + 1) + ' pages → dist (' + css + ', ' + js + ')' + (existsSync(relayPublic) ? '; design system copied to relay/public' : ''));
